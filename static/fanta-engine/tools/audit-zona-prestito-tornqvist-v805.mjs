import fs from 'node:fs';
import path from 'node:path';
const root=process.argv[2]||'.';
const read=(p)=>JSON.parse(fs.readFileSync(path.join(root,p),'utf8'));
let ok=0, fail=0;
const check=(c,m)=>{if(c){ok++;console.log('OK - '+m)}else{fail++;console.log('ERRORE - '+m)}};
const mani=read('static/zonaorientale/assets/rose/manifest.json');
const latest=mani.rosters?.[0];
check(latest?.id==='2026-2027-2026-09-09','manifest rose punta al 9 settembre');
check(latest?.file==='2026-2027-2026-09-09.json','file rosa corrente corretto');
const rose=read('static/zonaorientale/assets/rose/2026-2027-2026-09-09.json');
const beetle=rose.rosters.find(r=>r.name==='Beetlejuice');
const paper=rose.rosters.find(r=>r.name==='As Paperopoli');
check(Boolean(beetle&&paper),'Beetlejuice e As Paperopoli presenti');
check(!beetle.players.some(p=>p.playerName==='Tornqvist'),'Tornqvist rimosso dalla rosa utilizzabile Beetlejuice');
const tp=paper.players.find(p=>p.playerName==='Tornqvist');
check(Boolean(tp),'Tornqvist presente in As Paperopoli');
check(tp?.loanType==='FREE_LOAN'&&tp?.loanFee===0,'prestito marcato gratuito');
check(tp?.contractOwner==='Beetlejuice','cartellino resta Beetlejuice');
check(tp?.loanOriginalCost===1,'costo originario preservato');
check(tp?.cost===0,'costo prestito Paperopoli pari a zero');
check(rose.rosters.reduce((n,r)=>n+r.players.length,0)===288,'totale rose resta 288');
check(new Set(rose.rosters.flatMap(r=>r.players.map(p=>p.playerName.toLowerCase()))).size===288,'nessun giocatore duplicato tra rose');
const snap=read('static/zonaorientale/assets/snapshots/seasons/2026-2027.json');
const active=snap.rosterEntries.filter(e=>String(e.status||'ACTIVE').toUpperCase()!=='REMOVED');
const torn=active.filter(e=>e.playerName==='Tornqvist');
check(torn.length===1,'snapshot ha un solo Tornqvist attivo');
check(torn[0]?.seasonTeamId==='2026_2027_7bx0cegbxtf4fwh6t0pi','snapshot Tornqvist assegnato a Paperopoli');
check(torn[0]?.contractOwnerSeasonTeamId==='2026_2027_team_002','snapshot conserva proprietario Beetlejuice');
check(active.some(e=>e.playerName==='Gosens'&&e.seasonTeamId==='2026_2027_team_002'),'Gosens carryover preservato a Beetlejuice');
check(active.some(e=>e.playerName==='Maripan'&&e.seasonTeamId==='2026_2027_ulwtimbi3dyyrq0soesx'),'Maripan carryover preservato a River Plaid');
const mov=snap.fmMovements.find(m=>m.id==='prestito_tornqvist_2026_09_09_beetlejuice_paperopoli');
check(Boolean(mov),'movimento storico prestito presente');
check(mov?.amount===0&&mov?.operationSubtype==='PRESTITO_GRATUITO','movimento non altera FM');
const news=snap.news.find(n=>n.id==='prestito_tornqvist_beetlejuice_paperopoli_2026_09_09');
check(Boolean(news)&&/prestito gratuito/i.test(news.body||''),'comunicato ufficiale presente');
const g3=snap.competitionMatches.filter(m=>m.competitionId==='2026-2027_campionato'&&Number(m.leagueMatchday)===3);
check(g3.length===5&&g3.every(m=>m.status==='GIOCATA'&&m.matchDate==='2026-09-06'),'terza giornata preservata');
console.log(`Audit prestito Tornqvist V805: ${ok}/${ok+fail}`);
if(fail) process.exit(1);
