#!/usr/bin/env node
import fs from 'node:fs'; import path from 'node:path';
const root=path.resolve(process.argv[2]||'.');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const data=JSON.parse(read('static/fanta-engine/data/sudatori/current/sudatori-runtime.json'));
const manifest=JSON.parse(read('static/fanta-engine/data/sudatori/current/manifest.json'));
let checks=0; function ok(c,m){checks++;if(!c)throw new Error(m);}
ok(manifest.version==='V765','manifest versione '+manifest.version);
ok(manifest.appVersion==='V765','appVersion '+manifest.appVersion);
ok(data.meta.version==='V765','runtime versione '+data.meta.version);
ok(manifest.sourceFile.includes('v150_'),'sorgente non V150');
const index=read('static/iosudo/index.html'); const sw=read('static/iosudo/sw.js');
ok(index.includes('iosudo-app-v765.js?v=765'),'JS V765 non referenziato');
ok(index.includes('iosudo-app-v765.css?v=765'),'CSS V765 non referenziato');
ok(index.includes('aria-label="Versione applicazione V765">V765</span>'),'header V765 non aggiornato');
ok(index.includes('<title>ioSudo V765 - Per i SUDATORI</title>'),'title V765 non aggiornato');
ok(sw.includes("iosudo-shell-v765"),'cache V765 non aggiornata');
const roster=Object.values(data.playersByTeam||{}).flat();
const rosterById=new Map(roster.map(p=>[String(p.id||''),p]));
const directory=data.playerDirectory||[];
const players=directory.map(entry=>rosterById.has(String(entry.id||''))?Object.assign({},rosterById.get(String(entry.id)),entry):entry);
const byId=new Map(players.map(p=>[p.id,p]));
ok(byId.size===players.length,'ID giocatori duplicati');
const displayNames=players.map(p=>(p.playerName||'').normalize('NFD').replace(/[̀-ͯ]/g,'').toLowerCase().replace(/[^a-z0-9]+/g,' ').trim()).filter(Boolean);
ok(new Set(displayNames).size===displayNames.length,'nomi visualizzati duplicati');
ok(!players.some(p=>(p.playerName||'').includes('/')),'pseudo-giocatore con nomi uniti da slash');
ok(!players.some(p=>/^Autogol/i.test(p.playerName||'')),'autogol registrato come giocatore');
ok(new Set(roster.map(p=>p.id)).size===roster.length,'duplicati nel roster tecnico');
const find=id=>byId.get(id); const assertPlayer=(id,name,team,role)=>{const p=find(id);ok(!!p,'manca '+id);ok(p.playerName===name,id+' nome '+p.playerName);ok(p.teamName===team,id+' squadra '+p.teamName);ok(p.role===role,id+' ruolo '+p.role);};
assertPlayer('bologna-pessina-mas','Massimo Pessina','Bologna','P');
assertPlayer('monza-pessina-mas','Matteo Pessina','Monza','C');
assertPlayer('venezia-akor-adams','Akor Adams','Venezia','A');
assertPlayer('listone-6646','Che Adams','Torino','A');
assertPlayer('atalanta-giovane-atalanta','Samuel Giovane','Atalanta','C');
assertPlayer('napoli-giovane-napoli','Giovane Santana do Nascimento','Napoli','A');
assertPlayer('milan-yunus-musah','Yunus Musah','Milan','C');
ok(!players.some(p=>/Rabby Nzingoula Massolin/i.test(p.playerName||'')),'fusione Massolin/Nzingoula presente');
const listone=players.filter(p=>p.listone||p.fantacalcioId);
ok(listone.length===663,'righe listone rappresentate '+listone.length);
ok(listone.every(p=>(p.sourceKindsV765||p.sourceKindsV757||[]).includes('LISTONE')),'giocatore listone senza sorgente LISTONE');
ok(find('listone-6646').publicSourceV765==='LISTONE','Che Adams non marcato LISTONE');
const market=Object.entries(data.marketSummaryByTeam||{}).filter(([k])=>k!=='globale').flatMap(([,v])=>[...(v.officialIncoming||[]),...(v.officialOutgoing||[]),...(v.talksIncoming||[]),...(v.talksOutgoing||[]),...(v.injuries||[])]);
const formations=Object.values(data.formationsByTeam||{}).flat(); const stats=Object.values(data.friendlyPlayerStatsByMatch||{}).flatMap(x=>x.players||[]);
for(const x of [...market,...formations,...stats]) ok(!!x.canonicalPlayerId&&byId.has(x.canonicalPlayerId),'riga senza identità: '+(x.playerName||x.event||'?'));
const opKey=x=>[x.teamId,x.canonicalPlayerId,x.direction||'',x.date||'',x.url||'',!!x.isTransfermarktRumor].join('|');
const officialFlat=Object.entries(data.marketSummaryByTeam||{}).filter(([k])=>k!=='globale').flatMap(([,v])=>[...(v.officialIncoming||[]),...(v.officialOutgoing||[])]);
const talksFlat=Object.entries(data.marketSummaryByTeam||{}).filter(([k])=>k!=='globale').flatMap(([,v])=>[...(v.talksIncoming||[]),...(v.talksOutgoing||[])]);
ok(new Set(officialFlat.map(opKey)).size===officialFlat.length,'ufficialità operative duplicate');
ok(new Set(talksFlat.map(opKey)).size===talksFlat.length,'trattative operative duplicate');
ok(manifest.officialMoves===447,'conteggio ufficialità');
ok(manifest.teamTransferTalks===206,'conteggio trattative');
ok(manifest.transfermarktRumors===15,'conteggio TM');
ok(manifest.injuries===27,'conteggio infortuni');
ok(manifest.friendlies===107,'conteggio amichevoli');
ok(manifest.friendlyPlayerStats===550,'conteggio prestazioni');
ok((data.marketSummaryByTeam.roma?.talksIncoming||[]).some(x=>x.playerName==='Antonio Nusa'&&x.date==='2026-07-23'),'rumor Antonio Nusa non aggiornato');
ok((data.friendliesByTeam.roma||[]).some(x=>/Roma-Trastevere/i.test(x.event||'')&&x.date==='2026-07-23'),'Roma-Trastevere mancante');
ok((data.marketSummaryByTeam.lecce?.officialOutgoing||[]).some(x=>/Ramadani/i.test(x.playerName||'')&&/orum FK/i.test(x.destination||'')),'Ramadani non corretto al Çorum FK');
console.log(`Audit ioSudo V765 OK - ${checks} controlli superati - giocatori ${players.length}, roster ${roster.length}.`);
