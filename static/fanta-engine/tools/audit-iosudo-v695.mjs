import fs from 'node:fs';
const manifest = JSON.parse(fs.readFileSync('static/fanta-engine/data/sudatori/current/manifest.json','utf8'));
const index = fs.readFileSync('static/iosudo/index.html','utf8');
const sw = fs.readFileSync('static/iosudo/sw.js','utf8');
const data = JSON.parse(fs.readFileSync('static/fanta-engine/data/sudatori/current/sudatori-data.json','utf8'));
if (manifest.version !== 'V695') throw new Error('manifest non V695');
if (!manifest.updatedAtTime || !String(manifest.updatedAtTime).includes('T')) throw new Error('updatedAtTime assente o senza ora');
if (!index.includes('iosudo-app-v695.js?v=695')) throw new Error('index non punta al JS V695');
if (!sw.includes('iosudo-shell-v695')) throw new Error('service worker non V695');
if (!data.marketSummaryByTeam || !data.playersByTeam) throw new Error('dati principali mancanti');
const allPlayers = Object.values(data.playersByTeam).flat();
const key = (p) => [String(p.playerName||'').toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g,'').replace(/[^a-z0-9]+/g,' ').trim(), p.role||'', p.teamId||''].join('::');
const dup = new Map();
allPlayers.forEach((p) => dup.set(key(p), (dup.get(key(p))||0)+1));
const duplicates = Array.from(dup.entries()).filter(([k,v]) => k.split('::')[0] && v>1);
if (duplicates.length) throw new Error('duplicati in playersByTeam: '+duplicates.slice(0,5).map(x=>x[0]).join(', '));
const falseSos = allPlayers.filter((p) => p.sosFantaFlag && !((data.injuriesByTeam[p.teamId]||[]).some((i)=>String(i.playerName||'').toLowerCase()===String(p.playerName||'').toLowerCase())));
if (falseSos.length) throw new Error('sosFantaFlag impropri in Rosa: '+falseSos.slice(0,5).map(p=>p.playerName).join(', '));
console.log('Audit ioSudo V695 OK', JSON.stringify({players: manifest.players, officialMoves: manifest.officialMoves, talks: manifest.teamTransferTalks, injuries: manifest.injuries, updatedAtTime: manifest.updatedAtTime}));
