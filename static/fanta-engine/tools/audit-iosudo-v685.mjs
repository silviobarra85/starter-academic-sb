import { readFileSync } from 'node:fs';

const read = (path) => readFileSync(path, 'utf8');
const index = read('static/iosudo/index.html');
const sw = read('static/iosudo/sw.js');
const app = read('static/fanta-engine/js/apps/iosudo-app-v685.js');
const manifest = JSON.parse(read('static/fanta-engine/data/sudatori/current/manifest.json'));
const data = JSON.parse(read('static/fanta-engine/data/sudatori/current/sudatori-data.json'));
function assertOk(condition, message) { if (!condition) throw new Error(message); }
assertOk(index.includes('iosudo-app-v685.js?v=685'), 'index non punta al JS V685');
assertOk(index.includes('iosudo-app-v685.css?v=685'), 'index non punta al CSS V685');
assertOk(index.includes('data-iosudo-version="685"'), 'data-iosudo-version non aggiornato a 685');
assertOk(sw.includes('iosudo-shell-v685'), 'service worker non usa cache V685');
assertOk(String(manifest.uiVersion) === '685', 'manifest uiVersion non aggiornato');
assertOk(String(data.meta.uiVersion) === '685', 'data meta uiVersion non aggiornato');
assertOk(manifest.sourceFile.includes('v35'), 'manifest non punta al file v35');
assertOk(manifest.players === 716, 'conteggio giocatori inatteso');
assertOk(manifest.friendlies === 92, 'conteggio amichevoli inatteso');
assertOk(manifest.teamTransferTalks === 558, 'conteggio trattative inatteso');
assertOk(manifest.officialIncoming === 148, 'conteggio ufficialita entrata inatteso');
assertOk(manifest.officialOutgoing === 156, 'conteggio ufficialita uscita inatteso');
assertOk(manifest.officialMoves === 304, 'conteggio ufficialita inatteso');
assertOk(manifest.injuries === 16, 'conteggio SOS inatteso');
assertOk(manifest.sources === 376, 'conteggio fonti inatteso');
assertOk(Array.isArray(data.updateLogV685) && data.updateLogV685.length === 16, 'updateLogV685 non coerente');
assertOk(app.includes('addMarketOnlyPlayersToFastRows(rows, seen);') === false || app.includes('// addMarketOnlyPlayersToFastRows(rows, seen);'), 'GIOCATORI include ancora market-only player');
assertOk(app.includes('formatDateTime'), 'header data/ora non preservato');
assertOk(app.includes('groupedMarketRows(kind)'), 'raggruppamento mercato globale mancante');
assertOk(app.includes('renderTeamMarketPanel(team, summary)'), 'mercato squadra richiudibile mancante');
assertOk(app.includes('renderMarketSubsection') && app.includes('TRATTATIVE IN USCITA'), 'sottosezioni mercato squadra non aggiornate');
console.log('Audit ioSudo V685 OK', JSON.stringify({version:685, players:manifest.players, talks:manifest.teamTransferTalks, official:manifest.officialMoves, friendlies:manifest.friendlies, injuries:manifest.injuries, sources:manifest.sources, updateRows:data.updateLogV685.length}));
