import fs from 'node:fs';
import path from 'node:path';
const dataPath = path.join(process.cwd(), 'static/fanta-engine/data/sudatori/current/sudatori-data.json');
const manifestPath = path.join(process.cwd(), 'static/fanta-engine/data/sudatori/current/manifest.json');
const data = JSON.parse(fs.readFileSync(dataPath, 'utf8'));
const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
if ((manifest.current || manifest.dataFile) !== 'sudatori-data.json') throw new Error('manifest current/dataFile non valido');
if ((data.meta || {}).version !== 'V638') throw new Error('meta.version atteso V638');
if (!data.playersByTeam || !data.marketSummaryByTeam) throw new Error('dataset Sudatori incompleto');
console.log('OK audit Sudatori V638: dataset, manifest e riepiloghi presenti.');
