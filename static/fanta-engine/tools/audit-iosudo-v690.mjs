import { readFileSync } from 'node:fs';
const read = (path) => readFileSync(path, 'utf8');
const index = read('static/iosudo/index.html');
const sw = read('static/iosudo/sw.js');
const app = read('static/fanta-engine/js/apps/iosudo-app-v690.js');
const manifest = JSON.parse(read('static/fanta-engine/data/sudatori/current/manifest.json'));
const data = JSON.parse(read('static/fanta-engine/data/sudatori/current/sudatori-data.json'));
function assertOk(condition, message) { if (!condition) throw new Error(message); }
assertOk(index.includes('iosudo-app-v690.js?v=690'), 'index non punta al JS V690');
assertOk(index.includes('iosudo-app-v690.css?v=690'), 'index non punta al CSS V690');
assertOk(index.includes('data-iosudo-version="690"'), 'data-iosudo-version non aggiornato a 690');
assertOk(sw.includes('iosudo-shell-v690'), 'service worker non usa cache V690');
assertOk(String(manifest.uiVersion) === '690', 'manifest uiVersion non aggiornato');
assertOk(String(data.meta.uiVersion) === '690', 'data meta uiVersion non aggiornato');
assertOk(String(manifest.sourceFile || '').includes('v40'), 'manifest non punta al file v40');
assertOk(manifest.players === 717, 'conteggio giocatori inatteso');
assertOk(manifest.friendlies === 92, 'conteggio amichevoli inatteso');
assertOk(manifest.teamTransferTalks === 581, 'conteggio trattative inatteso');
assertOk(manifest.officialIncoming === 150, 'conteggio ufficialita entrata inatteso');
assertOk(manifest.officialOutgoing === 165, 'conteggio ufficialita uscita inatteso');
assertOk(manifest.officialMoves === 315, 'conteggio ufficialita inatteso');
assertOk(manifest.injuries === 16, 'conteggio SOS inatteso');
assertOk(manifest.sources === 470, 'conteggio fonti inatteso');
assertOk(Array.isArray(data.updateLogV690) && data.updateLogV690.length === 13, 'updateLogV690 non coerente');
assertOk(Boolean(manifest.updatedAtTime || data.meta.updatedAtTime || data.meta.generatedAt), 'data+ora header non disponibile');
assertOk(app.includes('formatDateTime'), 'header data/ora non preservato');
assertOk(app.includes('groupedMarketRows(kind)'), 'raggruppamento mercato globale mancante');
assertOk(app.includes('renderMarketSubsection') && app.includes('TRATTATIVE IN USCITA'), 'sottosezioni mercato squadra non aggiornate');
console.log('Audit ioSudo V690 OK', JSON.stringify({version:690, players:manifest.players, talks:manifest.teamTransferTalks, official:manifest.officialMoves, friendlies:manifest.friendlies, injuries:manifest.injuries, sources:manifest.sources, updateRows:data.updateLogV690.length, updatedAtTime:manifest.updatedAtTime}));
