import fs from 'node:fs';
import path from 'node:path';
const root = path.resolve(process.argv[2] || '.');
const readJson = p => JSON.parse(fs.readFileSync(path.join(root,p),'utf8'));
const assert = (c,m) => { if (!c) throw new Error(m); };
const runtime = readJson('static/fanta-engine/data/sudatori/current/sudatori-runtime.json');
const archive = readJson('static/fanta-engine/data/sudatori/current/sudatori-data.json');
const manifest = readJson('static/fanta-engine/data/sudatori/current/manifest.json');
const html = fs.readFileSync(path.join(root,'static/iosudo/index.html'),'utf8');
const sw = fs.readFileSync(path.join(root,'static/iosudo/sw.js'),'utf8');
assert(manifest.version === 'V774', `manifest versione ${manifest.version}`);
assert(runtime.meta.version === 'V774' && archive.meta.version === 'V774','payload non V774');
assert(html.includes('ioSudo V774') && html.includes('data-iosudo-version="774"'),'header non V774');
assert(html.includes('iosudo-app-v774.js?v=774') && html.includes('iosudo-app-v774.css?v=774'),'asset non V774');
assert(sw.includes('iosudo-shell-v774'),'cache non V774');
const roster = Object.values(runtime.playersByTeam).flat();
const dir = archive.playerDirectory;
const ids = dir.map(x=>x.id);
assert(new Set(ids).size===ids.length,'ID catalogo duplicati');
const fullById = new Map(roster.map(x=>[x.id,x]));
for (const x of dir) if (Object.keys(x).length>1) fullById.set(x.id,x);
const names=[...fullById.values()].map(x=>(x.canonicalFullName||x.playerName||'').trim().toLocaleLowerCase('it'));
assert(new Set(names).size===names.length,'nomi visualizzati duplicati');
const fantasy=[...fullById.values()].map(x=>String(x.fantacalcioId||x.listone?.fantacalcioId||'')).filter(Boolean);
assert(new Set(fantasy).size===fantasy.length,'ID Fantacalcio duplicati');
const fros=runtime.playersByTeam.frosinone;
const nap=runtime.playersByTeam.napoli;
assert(fros.some(x=>x.id==='napoli-alessio-zerbin'&&x.playerName==='Alessio Zerbin'),'Zerbin non al Frosinone');
assert(fros.some(x=>x.id==='napoli-hasa'&&x.playerName==='Luis Hasa'),'Hasa non al Frosinone');
assert(!nap.some(x=>x.id==='napoli-alessio-zerbin'||x.id==='napoli-hasa'),'Zerbin/Hasa ancora nel Napoli');
assert(nap.some(x=>x.id==='napoli-obaretin'&&x.playerName==='Nosa Obaretin'),'Nosa Obaretin non normalizzato');
assert(archive.teamTransferTalks.some(x=>x.canonicalPlayerId==='napoli-obaretin'&&x.teamId==='genoa'),'rumor Obaretin-Genoa assente');
assert(archive.teamTransferTalks.some(x=>x.canonicalPlayerId==='napoli-christian-garofalo'&&x.teamId==='genoa'),'rumor Garofalo-Genoa assente');
assert(!archive.teamTransferTalks.some(x=>['napoli-alessio-zerbin','napoli-hasa'].includes(x.canonicalPlayerId)),'rumor ufficializzati ancora attivi');
for (const pid of ['napoli-alessio-zerbin','napoli-hasa']) {
  assert(archive.officialMoves.some(x=>x.canonicalPlayerId===pid&&x.teamId==='frosinone'&&x.direction==='incoming'),'ufficialità Frosinone assente '+pid);
  assert(archive.officialMoves.some(x=>x.canonicalPlayerId===pid&&x.teamId==='napoli'&&x.direction==='outgoing'),'uscita Napoli assente '+pid);
}
assert(archive.injuries.some(x=>x.canonicalPlayerId==='milan-nkunku'),'SOS Nkunku assente');
const injuryIds=new Set(archive.injuries.map(x=>x.canonicalPlayerId));
for (const p of roster) assert(Boolean(p.sosFantaFlag)===injuryIds.has(p.id),'badge SOS incoerente '+p.id);
assert(Object.keys(runtime.formationsByTeam).length===20,'formazioni non 20');
assert(Object.values(runtime.formationsByTeam).flat().length===220,'slot formazione non 220');
for (const [team,arr] of Object.entries(runtime.formationsByTeam)) assert(arr.length===11,`XI ${team} non 11`);
const officialKeys=archive.officialMoves.map(x=>[x.teamId,x.direction,x.canonicalPlayerId,x.date,x.formula].join('|'));
assert(new Set(officialKeys).size===officialKeys.length,'ufficialità duplicate');
const talkKeys=archive.teamTransferTalks.map(x=>[x.teamId,x.direction,x.canonicalPlayerId].join('|'));
assert(new Set(talkKeys).size===talkKeys.length,'trattative duplicate');
const urls=archive.sources.map(x=>x.url).filter(Boolean);
assert(new Set(urls).size===urls.length,'fonti URL duplicate');
const mp=fullById.get('monza-pessina-mas'); const maxp=fullById.get('bologna-pessina-mas');
assert(mp&&mp.role==='C'&&mp.teamName==='Monza','Matteo Pessina errato');
assert(maxp&&maxp.role==='P'&&maxp.teamName==='Bologna','Massimo Pessina errato');
assert(fullById.has('lazio-filipe-bordon')&&fullById.has('lazio-ricardo-bordon'),'fratelli Bordon non distinti');
console.log(`Audit ioSudo V774 OK - catalogo ${dir.length}, roster ${roster.length}, ufficialita ${archive.officialMoves.length}, trattative ${archive.teamTransferTalks.length}, SOS ${archive.injuries.length}, fonti ${archive.sources.length}, duplicati 0.`);
