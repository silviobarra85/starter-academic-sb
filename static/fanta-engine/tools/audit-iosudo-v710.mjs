import fs from 'node:fs';
function assertOk(condition, message) { if (!condition) throw new Error(message); }
const index = fs.readFileSync('static/iosudo/index.html', 'utf8');
const sw = fs.readFileSync('static/iosudo/sw.js', 'utf8');
const js = fs.readFileSync('static/fanta-engine/js/apps/iosudo-app-v710.js', 'utf8');
const css = fs.readFileSync('static/fanta-engine/css/iosudo-app-v710.css', 'utf8');
const manifest = JSON.parse(fs.readFileSync('static/fanta-engine/data/sudatori/current/manifest.json', 'utf8'));
const data = JSON.parse(fs.readFileSync('static/fanta-engine/data/sudatori/current/sudatori-data.json', 'utf8'));
assertOk(index.includes('iosudo-app-v710.js?v=710'), 'index non punta al JS V710');
assertOk(index.includes('iosudo-app-v710.css?v=710'), 'index non punta al CSS V710');
assertOk(index.includes('data-iosudo-version="710"'), 'index non ha data-iosudo-version 710');
assertOk(sw.includes('iosudo-shell-v710'), 'service worker non usa cache V710');
assertOk(sw.includes('iosudo-app-v710.js?v=710'), 'service worker non cachea JS V710');
assertOk(sw.includes('iosudo-app-v710.css?v=710'), 'service worker non cachea CSS V710');
assertOk(manifest.version === 'V710', 'manifest non aggiornato a V710');
assertOk(data.meta?.version === 'V710', 'sudatori-data meta.version non aggiornato a V710');
assertOk((data.teams || []).length === 20, 'teams non sono 20');
assertOk(Object.keys(data.playersByTeam || {}).length === 20, 'playersByTeam incompleto');
assertOk(js.includes('function renderFriendlyDetail(matchKey, teamId)'), 'renderFriendlyDetail assente');
assertOk(css.includes('iosudo-friendly-badge'), 'CSS badge amichevoli assente');
const slug = (v) => String(v || '').normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase().replace(/[^a-z0-9]+/g,'-').replace(/^-|-$/g,'');
const seenExact = new Set(); const seenIds = new Set(); const exactDuplicates = []; const idDuplicates = [];
for (const [teamId, rows] of Object.entries(data.playersByTeam || {})) {
  for (const p of rows || []) {
    const key = [teamId, slug(p.playerName), String(p.role || '').toUpperCase().slice(0,1)].join('::');
    if (seenExact.has(key)) exactDuplicates.push(key); seenExact.add(key);
    const id = String(p.id || ''); if (!id) idDuplicates.push('missing-id'); else if (seenIds.has(id)) idDuplicates.push(id); seenIds.add(id);
  }
}
assertOk(exactDuplicates.length === 0, 'duplicati esatti in playersByTeam: ' + exactDuplicates.slice(0, 5).join(', '));
assertOk(idDuplicates.length === 0, 'ID giocatori duplicati: ' + idDuplicates.slice(0, 5).join(', '));
assertOk(manifest.dedupVersion && manifest.dedupVersion.includes('V710'), 'dedupVersion non aggiornata a V710');
assertOk(manifest.activeOfficialRumors === 0, 'restano rumor attivi per giocatori ufficiali: ' + manifest.activeOfficialRumors);
assertOk((data.activeOfficialRumorsAuditV710 || []).length === 0, 'activeOfficialRumorsAuditV710 non vuoto');
const genoaOfficials = data.officialMovesByTeam?.genoa || [];
const hamed = genoaOfficials.find((item) => /hamed-junior-traor/i.test(slug(item.playerName)) && /genoacfc\.it/.test(String(item.url || item.articleUrl || '')));
assertOk(Boolean(hamed), 'Hamed Junior Traorè ufficiale Genoa assente V710');
const lazioOfficials = data.officialMovesByTeam?.lazio || [];
const galassi = lazioOfficials.find((item) => /bruno galassi/i.test(String(item.playerName || '')) && /sslazio\.it/.test(String(item.url || item.articleUrl || '')));
assertOk(Boolean(galassi), 'Bruno Galassi ufficiale Lazio assente V710');
const lazioTalks = data.teamTransferTalksByTeam?.lazio || [];
assertOk(!lazioTalks.some((item) => /galassi/i.test(String(item.playerName || ''))), 'Galassi ancora nei rumor attivi V710');
const genoaTalks = data.teamTransferTalksByTeam?.genoa || [];
assertOk(!genoaTalks.some((item) => /traor|hamed/i.test(String(item.playerName || ''))), 'Traorè/Hamed ancora nei rumor attivi Genoa V710');
assertOk((data.officialTalksClosedV710 || []).length >= 9, 'Trattative chiuse V710 incomplete');
const buongiorno = (data.playersByTeam?.napoli || []).find((p) => /^buongiorno$/i.test(String(p.playerName || '')));
assertOk(buongiorno && /consulto chirurgico/i.test(String(buongiorno.injuryStatus || buongiorno.physicalStatus || '')), 'Buongiorno non aggiornato con consulto chirurgico');
assertOk(buongiorno && (buongiorno.sosFantaFlag === true || /infortun|indispon/i.test(String(buongiorno.injuryStatus || ''))), 'Buongiorno senza trigger badge SOS');
const buoInjury = (data.injuriesByTeam?.napoli || []).find((item) => /^buongiorno$/i.test(String(item.playerName || '')));
assertOk(buoInjury && /sscnapoli\.it\/nota-medica-alessandro-buongiorno/.test(String(buoInjury.url || '')), 'Buongiorno non presente in SOS/infortuni con fonte Napoli');
const patric = (data.playersByTeam?.lazio || []).find((p) => /^patric$/i.test(String(p.playerName || '')));
assertOk(patric && /sslazio\.it\/it\/news\/comunicati\/patric-temporaneamente-indisponibile/.test(String(patric.injurySource || '')), 'Patric senza fonte puntuale Lazio');
const sassuolo = data.friendliesByTeam?.sassuolo || [];
const sassuoloAlta = sassuolo.find((item) => String(item.event || '') === 'Sassuolo-Alta Anaunia');
assertOk(Boolean(sassuoloAlta), 'Sassuolo-Alta Anaunia non trovata');
assertOk(sassuoloAlta.hasPlayerStats === true, 'Sassuolo-Alta Anaunia senza flag hasPlayerStats');
assertOk(Array.isArray(sassuoloAlta.playerStats) && sassuoloAlta.playerStats.length === 26, 'Tabellino Sassuolo-Alta Anaunia non ha 26 righe');
assertOk(manifest.players === 777, 'Conteggio giocatori V710 inatteso: ' + manifest.players);
assertOk(manifest.officialMoves === 365, 'Conteggio ufficialita V710 inatteso: ' + manifest.officialMoves);
assertOk(manifest.teamTransferTalks === 459, 'Conteggio trattative attive V710 inatteso: ' + manifest.teamTransferTalks);
assertOk(manifest.injuries === 22, 'Conteggio infortuni V710 inatteso: ' + manifest.injuries);
console.log('Audit ioSudo V710 OK', JSON.stringify({ players: manifest.players, talks: manifest.teamTransferTalks, official: manifest.officialMoves, injuries: manifest.injuries, friendlies: manifest.friendlies, friendlyMatchDetails: manifest.friendlyMatchDetails, duplicateExact: 0 }));
