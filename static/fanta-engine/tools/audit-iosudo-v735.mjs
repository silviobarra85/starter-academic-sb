import fs from 'node:fs';
const data = JSON.parse(fs.readFileSync(new URL('../data/sudatori/current/sudatori-data.json', import.meta.url), 'utf8'));
const meta = data.meta || {};
const fail = (msg) => { console.error('Audit ioSudo V735 FAIL:', msg); process.exit(1); };
const norm = (s) => String(s || '').toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g,'').replace(/[^a-z0-9]+/g,' ').trim();
const arrs = (key) => Object.values(data[key] || {}).flatMap(v => Array.isArray(v) ? v : []);
const players = arrs('playersByTeam');
const ids = players.map(p => p.id).filter(Boolean);
if (meta.version !== 'V735') fail(`version ${meta.version}`);
if (new Set(ids).size !== ids.length) fail('ID giocatori duplicati');
if (meta.overlayGeneratedAt !== '2026-07-19T13:45:00+02:00') fail('timestamp overlay mancante');
if (!players.some(p => norm(p.playerName) === 'alessandro circati')) fail('Alessandro Circati mancante');
if (!players.some(p => norm(p.playerName) === 'adrian bernabe')) fail('Adrian Bernabe mancante');
if (!players.some(p => norm(p.playerName) === 'mathias lovik')) fail('Mathias Lovik mancante');
if (!players.some(p => norm(p.playerName) === 'patrick cutrone')) fail('Patrick Cutrone mancante');
if (!players.some(p => norm(p.playerName) === 'mario pasalic')) fail('Mario Pasalic mancante');
if (!players.some(p => norm(p.playerName) === 'david neres')) fail('David Neres mancante');
if (!players.some(p => norm(p.playerName) === 'mirko elia')) fail('Mirko Elia mancante');
if (!players.some(p => norm(p.playerName) === 'jacopo antolini')) fail('Jacopo Antolini mancante');

if (players.some(p => norm(p.playerName) === 'neres')) fail('Neres non normalizzato');
const official = arrs('officialMovesByTeam');
if (!official.some(x => norm(x.playerName)==='mirko elia' && norm(x.teamName)==='fiorentina')) fail('ufficialità Mirko Elia mancante');
if (!official.some(x => norm(x.playerName)==='jacopo antolini' && norm(x.teamName)==='torino')) fail('ufficialità Jacopo Antolini mancante');
const talks = arrs('teamTransferTalksByTeam').filter(x => !/chiusa|superata|duplicata/.test(norm(x.status)));
if (!talks.some(x => norm(x.playerName)==='alessio zerbin' && norm(x.teamName)==='frosinone')) fail('Zerbin Frosinone attivo mancante');
if (!talks.some(x => norm(x.playerName)==='alessio zerbin' && norm(x.teamName)==='napoli')) fail('Zerbin Napoli attivo mancante');
if ((meta.activeOfficialRumors || 0) !== 0) fail('rumor attivi su ufficialità');
if (!Array.isArray(data.duplicatePairCandidatesV735) || data.duplicatePairCandidatesV735.length !== 10) fail('coppie candidati duplicate mancanti');
console.log('Audit ioSudo V735 OK');
console.log(JSON.stringify({ version: meta.version, players: meta.players, officialMoves: meta.officialMoves, teamTransferTalks: meta.teamTransferTalks, injuries: meta.injuries, friendlies: meta.friendlies, friendlyMatchDetails: meta.friendlyMatchDetails, friendlyPlayerStats: meta.friendlyPlayerStats, sources: meta.sources, aliasRows: meta.aliasRows, overlayGeneratedAt: meta.overlayGeneratedAt }, null, 2));
