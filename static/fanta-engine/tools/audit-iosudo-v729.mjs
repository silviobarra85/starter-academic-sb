import fs from 'node:fs';
const data = JSON.parse(fs.readFileSync(new URL('../data/sudatori/current/sudatori-data.json', import.meta.url), 'utf8'));
const meta = data.meta || {};
const fail = (msg) => { console.error('Audit ioSudo V729 FAIL:', msg); process.exit(1); };
const norm = (s) => String(s || '').toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g,'').replace(/[^a-z0-9]+/g,' ').trim();
const arrs = (key) => Object.values(data[key] || {}).flatMap(v => Array.isArray(v) ? v : []);
const players = arrs('playersByTeam');
const ids = players.map(p => p.id).filter(Boolean);
if (meta.version !== 'V729') fail(`version ${meta.version}`);
if (new Set(ids).size !== ids.length) fail('ID giocatori duplicati');
if (meta.players !== 1038) fail(`conteggio giocatori atteso 1038, trovato ${meta.players}`);
if (players.some(p => p.teamId === 'atalanta' && norm(p.playerName) === 'ederson d s')) fail('Ederson D.S. ancora presente come giocatore separato');
if (!players.some(p => p.teamId === 'atalanta' && norm(p.playerName) === 'ederson')) fail('Ederson canonico mancante');
if (!players.some(p => p.teamId === 'parma' && norm(p.playerName) === 'mateusz kowalski')) fail('Mateusz Kowalski non normalizzato');
if (!players.some(p => p.teamId === 'udinese' && norm(p.playerName) === 'giulio vinciati')) fail('Giulio Vinciati mancante');
const basileaItem = (data.friendliesByTeam?.juventus || []).find(x => norm(x.event) === 'basilea juventus');
if (!basileaItem || basileaItem.result !== '0-0') fail('Basilea-Juventus senza result 0-0 su item');
const basileaDetail = data.friendlyPlayerStatsByMatch?.['juventus 2026 07 18 basilea juventus'];
if (!basileaDetail || basileaDetail.result !== '0-0') fail('Basilea-Juventus senza result 0-0 su detail');
const udinese = data.friendlyPlayerStatsByMatch?.['udinese 2026 07 18 udinese nk istra'];
if (!udinese) fail('tabellino Udinese-NK Istra mancante');
if ((udinese.players || []).length !== 21) fail(`righe Udinese attese 21, trovate ${(udinese.players || []).length}`);
if ((udinese.totals || {}).goals !== 2) fail('gol Udinese attesi 2');
const torino = data.friendlyPlayerStatsByMatch?.['torino 2026 07 18 torino pinzolo valrendena'];
if (!torino || torino.result !== '13-0') fail('Torino-Pinzolo non corretto a 13-0');
const monza = (data.friendliesByTeam?.monza || []).find(x => norm(x.event) === 'monza pro vercelli');
if (!monza || monza.result !== '4-3') fail('Monza-Pro Vercelli senza result 4-3');
if ((meta.activeOfficialRumors || 0) !== 0) fail('rumor attivi su ufficialità');
console.log('Audit ioSudo V729 OK');
console.log(JSON.stringify({ version: meta.version, players: meta.players, playersRows: meta.playersRows, officialMoves: meta.officialMoves, teamTransferTalks: meta.teamTransferTalks, injuries: meta.injuries, friendlies: meta.friendlies, friendlyMatchDetails: meta.friendlyMatchDetails, friendlyPlayerStats: meta.friendlyPlayerStats, sources: meta.sources }, null, 2));
