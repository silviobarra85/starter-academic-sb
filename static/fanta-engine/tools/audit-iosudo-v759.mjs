import fs from 'node:fs';
import path from 'node:path';
const root = process.argv[2] ? path.resolve(process.argv[2]) : process.cwd();
const read = (rel) => fs.readFileSync(path.join(root, rel), 'utf8');
const json = (rel) => JSON.parse(read(rel));
const fail = (m) => { throw new Error(m); };
const checks = [];
const check = (c,m) => { if (!c) fail(m); checks.push(m); };
const norm = (v) => String(v || '').toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g,'').replace(/[^a-z0-9]+/g,' ').trim();
const data = json('static/fanta-engine/data/sudatori/current/sudatori-data.json');
const runtime = json('static/fanta-engine/data/sudatori/current/sudatori-runtime.json');
const manifest = json('static/fanta-engine/data/sudatori/current/manifest.json');
const html = read('static/iosudo/index.html');
const sw = read('static/iosudo/sw.js');
const js = read('static/fanta-engine/js/apps/iosudo-app-v759.js');
const players = Object.values(runtime.playersByTeam || {}).flat();
const byId = new Map(players.map(p => [p.id,p]));
check(manifest.version === 'V759' && runtime.meta?.version === 'V759' && data.meta?.version === 'V759','versioni dati V759');
check(html.includes('iosudo-app-v759.js?v=759') && html.includes('iosudo-app-v759.css?v=759'),'index asset V759');
check(sw.includes("iosudo-shell-v759"),'cache PWA V759');
check(js.includes("identityMode: 'full-name-team-scoped'"),'diagnostica identità V759');
const musah = byId.get('milan-yunus-musah');
check(Boolean(musah),'Yunus Musah presente');
check(musah.teamId === 'milan' && musah.teamName === 'Milan','Yunus Musah corrente nel Milan');
check(musah.role === 'C' && musah.roleSource === 'LISTONE','Yunus Musah C da listone');
check(musah.realTeamCurrent === 'Milan' && musah.listoneTeamAtLoad === 'Atalanta','Musah distingue squadra corrente e fotografia listone');
check(!players.some(p => p.id !== musah.id && norm(p.playerName) === 'yunus musah'),'nessun duplicato Yunus Musah');
const ata = byId.get('atalanta-giovane-atalanta');
const nap = byId.get('napoli-giovane-napoli');
check(Boolean(ata) && Boolean(nap),'entrambe le identità Giovane presenti');
check(ata.playerName === 'Samuel Giovane' && ata.teamId === 'atalanta' && ata.role === 'C','Samuel Giovane Atalanta C');
check(nap.playerName === 'Giovane Santana do Nascimento' && nap.teamId === 'napoli' && nap.role === 'A','Giovane Santana do Nascimento Napoli A');
check(ata.id !== nap.id,'ID Giovane distinti');
check(!(ata.nameAliasesV755 || []).includes('Giovane Santana do Nascimento'),'Samuel Giovane non eredita alias Napoli');
check(!(nap.nameAliasesV755 || []).includes('Samuel Giovane'),'Giovane Napoli non eredita alias Atalanta');
const activeText = JSON.stringify({playersByTeam:runtime.playersByTeam,marketSummaryByTeam:runtime.marketSummaryByTeam,injuriesByTeam:runtime.injuriesByTeam,friendliesByTeam:runtime.friendliesByTeam,friendlyPlayerStatsByMatch:runtime.friendlyPlayerStatsByMatch});
check(!activeText.includes('Giovane (Atalanta)') && !activeText.includes('Giovane (Napoli)'),'nessuna etichetta Giovane con squadra tra parentesi');
const napStats = Object.values(runtime.friendlyPlayerStatsByMatch || {}).flatMap(m => m.players || []).filter(x => x.canonicalPlayerId === nap.id || (x.teamId === 'napoli' && norm(x.playerName).includes('giovane')));
check(napStats.every(x => x.playerName === 'Giovane Santana do Nascimento'),'tabellini Napoli collegati al nome completo');
const ids = new Set();
for (const p of players) { if (ids.has(p.id)) fail(`ID duplicato ${p.id}`); ids.add(p.id); }
check(players.length === manifest.rosterPlayers,'conteggio giocatori di rosa coerente');
check((runtime.playerDirectory || []).length === manifest.players,'catalogo completo coerente con manifest');
console.log(`Audit ioSudo V759 OK - ${checks.length} controlli superati`);
