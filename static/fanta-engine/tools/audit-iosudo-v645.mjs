#!/usr/bin/env node
import fs from 'fs';
import path from 'path';
const root = process.cwd();
const appPath = path.join(root, 'static/fanta-engine/js/apps/iosudo-app-v645.js');
const cssPath = path.join(root, 'static/fanta-engine/css/iosudo-app-v645.css');
const indexPath = path.join(root, 'static/iosudo/index.html');
const swPath = path.join(root, 'static/iosudo/sw.js');
const app = fs.readFileSync(appPath, 'utf8');
const css = fs.readFileSync(cssPath, 'utf8');
const index = fs.readFileSync(indexPath, 'utf8');
const sw = fs.readFileSync(swPath, 'utf8');
if (!index.includes('data-iosudo-version="645"')) throw new Error('versione DOM ioSudo non aggiornata a 645');
if (!index.includes('iosudo-app-v645.js?v=645')) throw new Error('cache-buster JS ioSudo V645 mancante');
if (!index.includes('iosudo-app-v645.css?v=645')) throw new Error('cache-buster CSS ioSudo V645 mancante');
if (!sw.includes("iosudo-shell-v645")) throw new Error('service worker non aggiornato a V645');
if (!app.includes('playerRowsCache')) throw new Error('cache vista GIOCATORI non rilevata');
if (!app.includes('scheduleRenderResults')) throw new Error('debounce ricerca non rilevato');
if (!app.includes('preparePlayerRowForCache')) throw new Error('indice di ricerca giocatori non rilevato');
if (!app.includes('iosudo-pitch-fantasy')) throw new Error('fantasy squadra nel probabile XI non rilevata');
if (!css.includes('.iosudo-pitch-fantasy')) throw new Error('stile fantasy squadra nel probabile XI mancante');
console.log('Audit ioSudo V645 OK', JSON.stringify({ cache:true, debounce:true, xiFantasy:true }));
