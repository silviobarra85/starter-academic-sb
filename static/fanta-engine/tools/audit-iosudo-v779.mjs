import fs from 'node:fs';
import path from 'node:path';
const root=path.resolve(process.argv[2]||'.');
const dir=path.join(root,'static/fanta-engine/data/sudatori/current');
const manifest=JSON.parse(fs.readFileSync(path.join(dir,'manifest.json'),'utf8'));
const data=JSON.parse(fs.readFileSync(path.join(dir,'sudatori-runtime.json'),'utf8'));
const archive=JSON.parse(fs.readFileSync(path.join(dir,'sudatori-data.json'),'utf8'));
const assert=(c,m)=>{if(!c)throw new Error(m)};
assert(manifest.version==='V779','manifest non V779');
const html=fs.readFileSync(path.join(root,'static/iosudo/index.html'),'utf8');
assert(html.includes('V779')&&html.includes('iosudo-app-v779.js?v=779'),'header/app non V779');
assert(fs.readFileSync(path.join(root,'static/iosudo/sw.js'),'utf8').includes('iosudo-shell-v779'),'cache non V779');
let incoming=0,outgoing=0,other=0; const keys=[];
for(const s of Object.values(data.marketSummaryByTeam||{})){
 incoming+=(s.talksIncoming||[]).length; outgoing+=(s.talksOutgoing||[]).length; other+=(s.talksOther||[]).length;
 for(const t of [...(s.talksIncoming||[]),...(s.talksOutgoing||[]),...(s.talksOther||[])]) keys.push(`${t.teamId}|${t.canonicalPlayerId}|${t.direction}`);
}
assert(incoming+outgoing+other===176,`rumor runtime ${incoming+outgoing+other}/176`);
assert(new Set(keys).size===keys.length,'trattative duplicate');
assert(archive.officialMoves.length===277,'ufficialita non 277');
assert(archive.officialMoves.some(x=>x.canonicalPlayerId==='napoli-vergara'&&x.isRenewal),'rinnovo Vergara assente');
assert(!archive.officialMoves.some(x=>x.canonicalPlayerId==='cagliari-demi-akarakiri'&&x.date==='2026-07-11'),'Akarakiri generico non rimosso');
assert((data.playerDirectory||[]).some(x=>x.id==='cagliari-juan-fernando-quintero'),'Quintero assente');
const qt=Object.values(data.marketSummaryByTeam).flatMap(s=>s.talks||[]).filter(x=>x.canonicalPlayerId==='cagliari-juan-fernando-quintero');
assert(qt.length===1,'rumor Quintero non unico');
const ids=(data.playerDirectory||[]).map(x=>x.id); assert(ids.length===1122,'catalogo non 1122'); assert(new Set(ids).size===ids.length,'ID duplicati');
const stats=Object.values(data.friendlyPlayerStatsByMatch||{}).reduce((n,x)=>n+(x.players||[]).length,0);
assert(Object.keys(data.friendlyPlayerStatsByMatch||{}).length===32,'tabellini non 32'); assert(stats===664,'prestazioni non 664');
const verg=(data.playersByTeam.napoli||[]).find(x=>x.id==='napoli-vergara'); assert(verg&&verg.hasRenewal===true,'badge rinnovo Vergara assente');
console.log(`Audit ioSudo V779 OK - rumor ${incoming+outgoing+other} (${incoming} entrata, ${outgoing} uscita, ${other} altro), ufficialita 277, tabellini 32, prestazioni 664, duplicati 0.`);
