import fs from 'node:fs';
import path from 'node:path';
const root=path.resolve(process.argv[2]||process.cwd());
const base=fs.existsSync(path.join(root,'static','zonaorientale'))?path.join(root,'static'):root;
const read=(...p)=>fs.readFileSync(path.join(base,...p),'utf8');
const app=read('zonaorientale','assets','app.js');
const firebase=read('zonaorientale','assets','firebase.js');
const adapter=read('fanta-engine','js','firebase','firebase-adapter-v499.js');
const release=JSON.parse(read('zonaorientale','release.json'));
const checks=[]; const c=(ok,msg)=>{checks.push([!!ok,msg]); console.log(`${ok?'OK':'FAIL'} - ${msg}`)};
c(release.version==='806','release V806');
c(app.includes('forgotPasswordBtn'),'pulsante Password dimenticata presente');
c(app.includes('await sendPasswordResetEmail(auth, email)'),'handler reset password usa Firebase');
c(app.includes('Inserisci l\'indirizzo email del tuo account'),'email obbligatoria prima del reset');
c(app.includes('Se l\'indirizzo è associato a un account'),'messaggio neutro anti-enumerazione account');
c(firebase.includes('sendPasswordResetEmail'),'wrapper ZonaOrientale esporta reset password');
c(adapter.includes('sendPasswordResetEmail'),'adapter FantaEngine esporta reset password');
c(!app.includes('password attuale') && !app.includes('recupera la password esistente'),'nessun tentativo di leggere password esistente');
const fails=checks.filter(x=>!x[0]);
console.log(`Audit reset password V806: ${checks.length-fails.length}/${checks.length}`);
if(fails.length) process.exit(1);
