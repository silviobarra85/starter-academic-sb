import { readFileSync } from 'node:fs';

const read = (path) => readFileSync(path, 'utf8');
const index = read('static/iosudo/index.html');
const sw = read('static/iosudo/sw.js');
const app = read('static/fanta-engine/js/apps/iosudo-app-v689.js');
const manifest = JSON.parse(read('static/fanta-engine/data/sudatori/current/manifest.json'));
const data = JSON.parse(read('static/fanta-engine/data/sudatori/current/sudatori-data.json'));
function assertOk(condition, message) { if (!condition) throw new Error(message); }
assertOk(index.includes('iosudo-app-v689.js?v=689'), 'index non punta al JS V689');
assertOk(index.includes('iosudo-app-v689.css?v=689'), 'index non punta al CSS V689');
assertOk(index.includes('data-iosudo-version="689"'), 'data-iosudo-version non aggiornato a 689');
assertOk(sw.includes('iosudo-shell-v689'), 'service worker non usa cache V689');
assertOk(String(manifest.uiVersion) === '689', 'manifest uiVersion non aggiornato');
assertOk(String(data.meta.uiVersion) === '689', 'data meta uiVersion non aggiornato');
assertOk(manifest.sourceFile.includes('v39'), 'manifest non punta al file v39');
assertOk(manifest.players === 717, 'conteggio giocatori inatteso');
assertOk(manifest.friendlies === 90, 'conteggio amichevoli inatteso');
assertOk(manifest.teamTransferTalks === 568, 'conteggio trattative inatteso');
assertOk(manifest.officialIncoming === 150, 'conteggio ufficialita entrata inatteso');
assertOk(manifest.officialOutgoing === 161, 'conteggio ufficialita uscita inatteso');
assertOk(manifest.officialMoves === 311, 'conteggio ufficialita inatteso');
assertOk(manifest.injuries === 16, 'conteggio SOS inatteso');
assertOk(manifest.sources === 455, 'conteggio fonti inatteso');
assertOk(Array.isArray(data.updateLogV689) && data.updateLogV689.length === 20, 'updateLogV689 non coerente');
assertOk(Boolean(manifest.updatedAtTime || data.meta.updatedAtTime || data.meta.generatedAt), 'data+ora header non disponibile');
assertOk(app.includes('formatDateTime'), 'header data/ora non preservato');
assertOk(app.includes('groupedMarketRows(kind)'), 'raggruppamento mercato globale mancante');
assertOk(app.includes('renderMarketSubsection') && app.includes('TRATTATIVE IN USCITA'), 'sottosezioni mercato squadra non aggiornate');
console.log('Audit ioSudo V689 OK', JSON.stringify({version:689, players:manifest.players, talks:manifest.teamTransferTalks, official:manifest.officialMoves, friendlies:manifest.friendlies, injuries:manifest.injuries, sources:manifest.sources, updateRows:data.updateLogV689.length, updatedAtTime:manifest.updatedAtTime}));
