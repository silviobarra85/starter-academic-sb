import fs from 'node:fs';
import path from 'node:path';
const root=process.argv[2]||'.';
const read=p=>JSON.parse(fs.readFileSync(path.join(root,p),'utf8'));
const m=read('static/fanta-engine/data/sudatori/current/manifest.json');
const d=read('static/fanta-engine/data/sudatori/current/sudatori-runtime.json');
const a=read('static/fanta-engine/data/sudatori/current/sudatori-data.json');
const assert=(c,msg)=>{if(!c) throw new Error(msg)};
assert(m.version==='V782','manifest versione '+m.version);
assert(d.meta.version==='V782','runtime versione '+d.meta.version);
assert(fs.readFileSync(path.join(root,'static/iosudo/index.html'),'utf8').includes('V782'),'header V782 assente');
assert(fs.readFileSync(path.join(root,'static/iosudo/sw.js'),'utf8').includes('iosudo-shell-v782'),'cache V782 assente');
const roster=Object.values(d.playersByTeam).flat();
assert(roster.length===814,'rose operative attese 814, trovate '+roster.length);
const ids=[...roster.map(x=>x.id),...d.playerDirectory.filter(x=>Object.keys(x).length>1).map(x=>x.id)];
assert(new Set(ids).size===ids.length,'ID canonici duplicati');
assert(Object.keys(d.formationsByTeam).length===20,'squadre XI non 20');
const forms=Object.values(d.formationsByTeam).flat();
assert(forms.length===220,'slot XI non 220');
for(const [tid,arr] of Object.entries(d.formationsByTeam)){assert(arr.length===11,tid+' non ha 11 titolari');assert(new Set(arr.map(x=>x.canonicalPlayerId)).size===11,tid+' XI duplicato')}
const injuries=Object.values(d.injuriesByTeam).flat();
assert(injuries.length===58,'SOS operativi attesi 58, trovati '+injuries.length);
const active=new Set(injuries.map(x=>x.canonicalPlayerId));
for(const p of roster) assert(Boolean(p.sosFlagActiveV782)===active.has(p.id),'badge SOS incoerente '+p.id);
const talks=Object.values(d.marketSummaryByTeam).flatMap(x=>x.talks||[]);
const talkKeys=talks.map(x=>[x.teamId,x.canonicalPlayerId,x.updatedAt,x.url,x.status].join('|'));
assert(new Set(talkKeys).size===talkKeys.length,'trattative duplicate');
assert(d.friendliesByTeam.atalanta.filter(x=>/Atalanta U23/i.test(x.event)).length===1,'Atalanta-Atalanta U23 duplicata');
assert(Object.values(d.friendliesByTeam).flat().filter(x=>/Basilea-Juventus \/ Bologna-Arminia/i.test(x.event)).length===0,'amichevole aggregata errata presente');
const byId=new Map([...roster,...d.playerDirectory.filter(x=>Object.keys(x).length>1)].map(x=>[x.id,x]));
assert(byId.get('monza-pessina-mas')?.role==='C','Matteo Pessina non C');
assert(byId.get('bologna-pessina-mas')?.role==='P','Massimo Pessina non P');
assert(byId.get('bologna-castro')?.teamName==='Roma','Castro non spostato a Roma con ID persistente');
assert(byId.get('roma-dovbyk')?.teamName==='Bologna','Dovbyk non spostato a Bologna con ID persistente');
assert(a.injuries.filter(x=>String(x.recordState).startsWith('CHIUSO')).length===9,'storico infortuni chiusi non 9');
assert(m.duplicateAuditV782.duplicateIds===0,'audit duplicati ID non zero');
assert(m.duplicateAuditV782.duplicateDisplayNames===0,'audit duplicati rosa non zero');
assert(m.duplicateAuditV782.duplicateTalkRows===0,'audit duplicati trattative non zero');
assert(m.duplicateAuditV782.duplicateOfficialRows===0,'audit duplicati ufficialita non zero');
assert(m.duplicateAuditV782.duplicateInjuryRows===0,'audit duplicati SOS non zero');
assert(m.duplicateAuditV782.duplicateFriendlyRows===0,'audit duplicati amichevoli non zero');
assert(m.duplicateAuditV782.duplicateFriendlyStatRows===0,'audit duplicati prestazioni non zero');
assert(byId.get('milan-kostic')?.canonicalFullName==='Andrej Kostić','Andrej Kostić Milan non disambiguato');
assert(byId.get('juventus-kostic')?.canonicalFullName==='Filip Kostic','Filip Kostic Juventus non disambiguato');
console.log(`Audit ioSudo V782 OK - catalogo ${m.players}, roster ${roster.length}, ufficialita ${m.officialMoves}, trattative ${talks.length}, SOS ${injuries.length}, amichevoli ${m.friendlies}, statistiche ${m.friendlyPlayerStats}, XI ${forms.length}, duplicati 0.`);
