import { readFileSync } from 'node:fs';

const read = (path) => readFileSync(path, 'utf8');
const index = read('static/iosudo/index.html');
const sw = read('static/iosudo/sw.js');
const app = read('static/fanta-engine/js/apps/iosudo-app-v686.js');
const manifest = JSON.parse(read('static/fanta-engine/data/sudatori/current/manifest.json'));
const data = JSON.parse(read('static/fanta-engine/data/sudatori/current/sudatori-data.json'));
function assertOk(condition, message) { if (!condition) throw new Error(message); }
assertOk(index.includes('iosudo-app-v686.js?v=686'), 'index non punta al JS V686');
assertOk(index.includes('iosudo-app-v686.css?v=686'), 'index non punta al CSS V686');
assertOk(index.includes('data-iosudo-version="686"'), 'data-iosudo-version non aggiornato a 686');
assertOk(sw.includes('iosudo-shell-v686'), 'service worker non usa cache V686');
assertOk(String(manifest.uiVersion) === '686', 'manifest uiVersion non aggiornato');
assertOk(String(data.meta.uiVersion) === '686', 'data meta uiVersion non aggiornato');
assertOk(manifest.sourceFile.includes('v36'), 'manifest non punta al file v36');
assertOk(manifest.players === 716, 'conteggio giocatori inatteso');
assertOk(manifest.friendlies === 92, 'conteggio amichevoli inatteso');
assertOk(manifest.teamTransferTalks === 565, 'conteggio trattative inatteso');
assertOk(manifest.officialIncoming === 148, 'conteggio ufficialita entrata inatteso');
assertOk(manifest.officialOutgoing === 156, 'conteggio ufficialita uscita inatteso');
assertOk(manifest.officialMoves === 304, 'conteggio ufficialita inatteso');
assertOk(manifest.injuries === 16, 'conteggio SOS inatteso');
assertOk(manifest.sources === 420, 'conteggio fonti inatteso');
assertOk(Array.isArray(data.updateLogV686) && data.updateLogV686.length === 17, 'updateLogV686 non coerente');
assertOk(app.includes('addMarketOnlyPlayersToFastRows(rows, seen);') === false || app.includes('// addMarketOnlyPlayersToFastRows(rows, seen);'), 'GIOCATORI include ancora market-only player');
assertOk(app.includes('formatDateTime'), 'header data/ora non preservato');
assertOk(app.includes('groupedMarketRows(kind)'), 'raggruppamento mercato globale mancante');
assertOk(app.includes('renderTeamMarketPanel(team, summary)'), 'mercato squadra richiudibile mancante');
assertOk(app.includes('renderMarketSubsection') && app.includes('TRATTATIVE IN USCITA'), 'sottosezioni mercato squadra non aggiornate');
const tomiyasu = (data.teamTransferTalksByTeam.sassuolo || []).find((x) => x.playerName === 'Takehiro Tomiyasu');
assertOk(tomiyasu && tomiyasu.updatedAt === '2026-07-15', 'Tomiyasu v36 non presente in trattative Sassuolo');
const clubSources = (data.sources || []).filter((x) => /Fonte ufficiale club|sito ufficiale/i.test(String(x.use || x.label || '')));
assertOk(clubSources.length >= 20, 'fonti ufficiali club non inserite');
console.log('Audit ioSudo V686 OK', JSON.stringify({version:686, players:manifest.players, talks:manifest.teamTransferTalks, official:manifest.officialMoves, friendlies:manifest.friendlies, injuries:manifest.injuries, sources:manifest.sources, updateRows:data.updateLogV686.length}));
