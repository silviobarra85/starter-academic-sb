import fs from 'node:fs';
import path from 'node:path';
const root=path.resolve(process.argv[2]||'.');
const read=(p)=>JSON.parse(fs.readFileSync(path.join(root,p),'utf8'));
const assert=(c,m)=>{if(!c) throw new Error(m)};
const manifest=read('static/fanta-engine/data/sudatori/current/manifest.json');
const runtime=read('static/fanta-engine/data/sudatori/current/sudatori-runtime.json');
const data=read('static/fanta-engine/data/sudatori/current/sudatori-data.json');
assert(manifest.version==='V773','manifest non V773');
assert(runtime.meta.version==='V773','runtime non V773');
assert(data.meta.version==='V773','archivio non V773');
const roster=Object.values(runtime.playersByTeam||{}).flat();
const rosterById=new Map(roster.map(x=>[x.id,x]));
const directory=runtime.playerDirectory||[];
const ids=directory.map(x=>x.id);
const fullCatalog=directory.map(x=>rosterById.get(x.id)||x);
const normalizeName=(value)=>String(value||'').normalize('NFD').replace(/[\u0300-\u036f]/g,'').toLowerCase().replace(/[^a-z0-9]+/g,' ').trim();
assert(ids.length===new Set(ids).size,'ID catalogo duplicati');
const displayNames=fullCatalog.map(x=>normalizeName(x.canonicalFullName||x.playerName)).filter(Boolean);
assert(displayNames.length===new Set(displayNames).size,'nomi completi duplicati');
const fantacalcioIds=fullCatalog.map(x=>x.fantacalcioId||x.listone?.fantacalcioId||x.listone?.id).filter(x=>x!==undefined&&x!==null&&String(x)!=='').map(String);
assert(fantacalcioIds.length===new Set(fantacalcioIds).size,'ID Fantacalcio duplicati');
assert(roster.length===manifest.rosterPlayers,'conteggio roster');
assert(ids.length===manifest.players,'conteggio catalogo');
const formations=Object.values(runtime.formationsByTeam||{}).flat();
assert(Object.keys(runtime.formationsByTeam||{}).length===20,'formazioni: squadre diverse da 20');
for(const [team,rows] of Object.entries(runtime.formationsByTeam||{})) assert(rows.length===11,`${team}: XI non composto da 11`);
assert(formations.length===220,'formazioni: slot diversi da 220');
const formationIds=formations.map(x=>x.canonicalPlayerId);
assert(formationIds.every(Boolean),'formazioni con ID canonico mancante');
assert(formationIds.length===new Set(formationIds).size,'giocatore duplicato nei probabili XI');
assert(formationIds.every(id=>ids.includes(id)),'probabile XI fuori catalogo');
for(const row of formations) {
  const p=rosterById.get(row.canonicalPlayerId)||fullCatalog.find(x=>x.id===row.canonicalPlayerId);
  assert(p?.probableXi===true,`flag XI mancante ${row.canonicalPlayerId}`);
  assert(p?.formationPosition===row.position,`posizione XI incoerente ${row.canonicalPlayerId}`);
}
const probablePlayers=fullCatalog.filter(x=>x.probableXi);
assert(probablePlayers.length===220,'flag probabile XI non pari a 220');
const bracaglia=rosterById.get('frosinone-bracaglia')||fullCatalog.find(x=>x.id==='frosinone-bracaglia');
assert(bracaglia?.role==='D','Bracaglia non è D');
assert(bracaglia?.playerName==='Gabriele Bracaglia','nome Bracaglia non completo');
assert(rosterById.get('monza-pessina-mas')?.role==='C','Matteo Pessina non C');
assert(!rosterById.has('bologna-pessina-mas') || rosterById.get('bologna-pessina-mas')?.role==='P','Massimo Pessina non P');
const injuryIds=new Set((data.injuries||[]).map(x=>x.canonicalPlayerId));
for(const p of roster) assert(Boolean(p.sosFantaFlag)===injuryIds.has(p.id),`badge SOS incoerente ${p.id}`);
const offKeys=(data.officialMoves||[]).map(x=>[x.teamId,x.direction,x.canonicalPlayerId,x.date,x.url].join('|'));
assert(offKeys.length===new Set(offKeys).size,'ufficialita duplicate');
const talkKeys=(data.teamTransferTalks||[]).map(x=>[x.teamId,x.direction,x.canonicalPlayerId].join('|'));
assert(talkKeys.length===new Set(talkKeys).size,'trattative duplicate');
const index=fs.readFileSync(path.join(root,'static/iosudo/index.html'),'utf8');
const sw=fs.readFileSync(path.join(root,'static/iosudo/sw.js'),'utf8');
assert(index.includes('V773')&&index.includes('iosudo-app-v773.js')&&index.includes('iosudo-app-v773.css'),'header/assets V773');
assert(sw.includes('iosudo-shell-v773'),'cache V773');
console.log(`Audit ioSudo V773 OK - 20 squadre, 220 probabili titolari, 11 per squadra, catalogo ${ids.length}, duplicati 0.`);
