import fs from 'node:fs';
import path from 'node:path';
const root=path.resolve(process.argv[2]||'.');
const read=(p)=>fs.readFileSync(path.join(root,p),'utf8');
const json=(p)=>JSON.parse(read(p));
let ok=0, fail=0;
function check(cond,msg){if(cond){console.log('OK - '+msg);ok++;}else{console.error('ERRORE - '+msg);fail++;}}
const release=json('static/zonaorientale/release.json');
const app=read('static/zonaorientale/assets/app.js');
const detail=read('static/zonaorientale/competition.html');
const manifest=json('static/zonaorientale/assets/competitions/manifest.json');
const camp=json('static/zonaorientale/assets/competitions/2026-2027/campionato-2026-2027.json');
const coppa=json('static/zonaorientale/assets/competitions/2026-2027/coppa-italia-2026-2027.json');
const champ=json("static/zonaorientale/assets/competitions/2026-2027/champions-league-2026-2027.json");
const snap=json('static/zonaorientale/assets/snapshots/seasons/2026-2027.json');
check(release.version==='796','release V796');
check(release.entrypoint==='assets/app.js?v=796','entrypoint V796');
check(Array.isArray(camp.matches)&&camp.matches.length===180,'Campionato: calendario completo di 180 partite');
check(camp.matches.filter(m=>m.status==='GIOCATA').length===10,'Campionato: prime 2 giornate/10 partite giocate preservate');
check(Array.isArray(champ.matches)&&champ.matches.length===8,"Champion's League: 8 quarti andata/ritorno");
check(coppa.competition?.format==='BATTLE_ROYALE','Coppa Italia: fase Battle Royale');
check(Array.isArray(coppa.matches)&&coppa.matches.length===0,'Coppa Italia: nessun calendario H2H fittizio');
check(Array.isArray(coppa.rounds)&&coppa.rounds.length===4,'Coppa Italia: 4 giornate Battle Royale');
check(JSON.stringify(coppa.rounds.map(r=>r.serieAMatchday))===JSON.stringify([8,17,24,26]),'Battle Royale sulle giornate Serie A 8,17,24,26');
check(coppa.rounds.every(r=>Array.isArray(r.participants)&&r.participants.length===10),'Ogni giornata Battle Royale ha 10 partecipanti');
check(coppa.rounds.every(r=>new Set(r.participants.map(p=>p.seasonTeamId)).size===10),'Partecipanti Battle Royale senza duplicati');
const cm=manifest.competitions.find(e=>e.id==='2026-2027-coppa-italia');
check(cm?.displayMode==='BATTLE_ROYALE'&&cm?.rounds===4,'Manifest Coppa Italia descrive Battle Royale');
const sc=snap.competitions.find(c=>c.id==='2026-2027_coppa_italia');
check(sc?.format==='BATTLE_ROYALE','Snapshot competizione allineato a Battle Royale');
check(detail.includes('renderBattleRoyaleRoundsV796'),'competition.html renderizza giornate Battle Royale');
check(detail.includes('Calendario completo della stagione'),'competition.html mantiene calendario per competizioni H2H');
check(detail.includes('battleRoyaleEntries'),'competition.html legge override risultati Battle Royale dallo snapshot');
check(app.includes('Risultati Battle Royale'),'Admin dedicato Battle Royale presente');
check(app.includes("entryMode:'BATTLE_ROYALE'"),'Admin salva risultati Battle Royale in competitionMatches');
check(app.includes("getDisputableCompetitionsForSeasonV796"),'Battle Royale esclusa dal form partite H2H');
check(app.includes('battleRoyaleNoCalendar:true'),'Contratto runtime no calendario Battle Royale presente');
check(app.includes('renderOpenCompetitionButtonV111'),'Apertura pagina dettaglio competizione preservata');
console.log(`\nAudit V796 competizioni: ${ok}/${ok+fail} controlli superati.`);
if(fail) process.exit(1);
