import fs from 'node:fs';
import path from 'node:path';
const root=process.argv[2]||'.';
const read=p=>JSON.parse(fs.readFileSync(path.join(root,p),'utf8'));
const m=read('static/fanta-engine/data/sudatori/current/manifest.json');
const d=read('static/fanta-engine/data/sudatori/current/sudatori-runtime.json');
const assert=(c,msg)=>{if(!c) throw new Error(msg)};
assert(m.version==='V776','manifest versione '+m.version);
assert(d.meta.version==='V776','runtime versione '+d.meta.version);
assert(fs.readFileSync(path.join(root,'static/iosudo/index.html'),'utf8').includes('V776'),'header V776 assente');
assert(fs.readFileSync(path.join(root,'static/iosudo/sw.js'),'utf8').includes('iosudo-shell-v776'),'cache V776 assente');
const roster=Object.values(d.playersByTeam).flat();
const ids=[...roster.map(x=>x.id),...d.playerDirectory.filter(x=>Object.keys(x).length>1).map(x=>x.id)];
assert(new Set(ids).size===ids.length,'ID canonici duplicati');
assert(!ids.includes('lazio-milani'),'Milani ancora nel catalogo');
assert(ids.includes('lazio-noah-markmann'),'Noah Markmann assente');
const injuries=Object.values(d.injuriesByTeam).flat();
assert(injuries.length===56,'SOS attesi 56, trovati '+injuries.length);
const active=new Set(injuries.map(x=>x.canonicalPlayerId));
for(const p of roster) assert(Boolean(p.sosFlagActiveV776)===active.has(p.id),'badge SOS incoerente '+p.id);
const forms=Object.values(d.formationsByTeam).flat();
assert(Object.keys(d.formationsByTeam).length===20,'squadre XI non 20');
assert(forms.length===220,'slot XI non 220');
for(const [tid,arr] of Object.entries(d.formationsByTeam)) assert(arr.length===11,tid+' non ha 11 titolari');
const talks=Object.values(d.marketSummaryByTeam).flatMap(x=>x.talks||[]);
const keys=talks.map(x=>[x.teamId,x.canonicalPlayerId,x.updatedAt,x.url].join('|'));
assert(new Set(keys).size===keys.length,'trattative duplicate');
const fullDirectory=new Map(d.playerDirectory.filter(x=>Object.keys(x).length>1).map(x=>[x.id,x]));
const pMat=roster.find(x=>x.id==='monza-pessina-mas')||fullDirectory.get('monza-pessina-mas');
const pMas=roster.find(x=>x.id==='bologna-pessina-mas')||fullDirectory.get('bologna-pessina-mas');
assert(pMat?.role==='C','Matteo Pessina non C');
assert(pMas?.role==='P','Massimo Pessina non P');
console.log(`Audit ioSudo V776 OK - catalogo ${m.players}, roster ${roster.length}, trattative ${talks.length}, SOS ${injuries.length}, XI ${forms.length}, duplicati 0.`);
