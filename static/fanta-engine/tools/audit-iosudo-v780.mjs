import fs from 'node:fs';
import path from 'node:path';
const root=path.resolve(process.argv[2]||'.');
const dir=path.join(root,'static/fanta-engine/data/sudatori/current');
const manifest=JSON.parse(fs.readFileSync(path.join(dir,'manifest.json'),'utf8'));
const data=JSON.parse(fs.readFileSync(path.join(dir,'sudatori-runtime.json'),'utf8'));
const archive=JSON.parse(fs.readFileSync(path.join(dir,'sudatori-data.json'),'utf8'));
const assert=(c,m)=>{if(!c)throw new Error(m)};
assert(manifest.version==='V780','manifest non V780');
const html=fs.readFileSync(path.join(root,'static/iosudo/index.html'),'utf8');
assert(html.includes('V780')&&html.includes('iosudo-app-v780.js?v=780'),'header/app non V780');
assert(fs.readFileSync(path.join(root,'static/iosudo/sw.js'),'utf8').includes('iosudo-shell-v780'),'cache non V780');
let incoming=0,outgoing=0,other=0; const talkKeys=[];
for(const s of Object.values(data.marketSummaryByTeam||{})){
 incoming+=(s.talksIncoming||[]).length; outgoing+=(s.talksOutgoing||[]).length; other+=(s.talksOther||[]).length;
 for(const t of [...(s.talksIncoming||[]),...(s.talksOutgoing||[]),...(s.talksOther||[])]) talkKeys.push(`${t.teamId}|${t.canonicalPlayerId}|${t.direction}`);
}
assert(incoming+outgoing+other===176,`rumor runtime ${incoming+outgoing+other}/176`);
assert(new Set(talkKeys).size===talkKeys.length,'trattative duplicate');
assert(archive.officialMoves.length===277,'ufficialita non 277');
const roster=Object.values(data.playersByTeam||{}).flat(); assert(roster.length===739,`roster ${roster.length}/739`);
assert(!roster.some(x=>x.id==='milan-bennacer'),'Bennacer ancora in rosa');
const directory=data.playerDirectory||[];
const ids=directory.map(x=>x.id); assert(ids.length===1123,`catalogo ${ids.length}/1123`); assert(new Set(ids).size===ids.length,'ID duplicati');
const resolvePlayer=id=>{const ref=directory.find(x=>x.id===id); if(!ref)return null; return Object.keys(ref).length===1 ? roster.find(x=>x.id===id)||null : ref;};
assert(!ids.includes('milan-bennacer'),'Bennacer ancora nel catalogo corrente');
assert(ids.includes('milan-vladimirov')&&ids.includes('milan-vos'),'nuovi profili tabellino Milan assenti');
const details=Object.keys(data.friendlyPlayerStatsByMatch||{}); const stats=Object.values(data.friendlyPlayerStatsByMatch||{}).reduce((n,x)=>n+(x.players||[]).length,0);
assert(details.length===33,`tabellini ${details.length}/33`); assert(stats===687,`prestazioni ${stats}/687`);
const celtic=data.friendlyPlayerStatsByMatch['milan 2026 07 25 celtic milan']; assert(celtic&&celtic.players.length===23&&celtic.result==='2-2','tabellino Celtic-Milan incompleto');
const injuries=Object.values(data.injuriesByTeam||{}).flat(); assert(injuries.length===57,`SOS ${injuries.length}/57`); assert(injuries.some(x=>x.canonicalPlayerId==='milan-gila'),'SOS Gila assente');
const gila=roster.find(x=>x.id==='milan-gila'); assert(gila&&gila.sosFantaFlag===true,'badge SOS Gila assente');
const findTalk=(team,id,dir)=>[...(data.marketSummaryByTeam[team]?.talksIncoming||[]),...(data.marketSummaryByTeam[team]?.talksOutgoing||[]),...(data.marketSummaryByTeam[team]?.talksOther||[])].find(x=>x.canonicalPlayerId===id&&x.direction===dir);
assert(findTalk('juventus','juventus-lois-openda','outgoing')?.status.includes('COMUNICATO ATTESO'),'Openda non aggiornato');
assert(findTalk('fiorentina','juventus-joao-mario','incoming')?.status.includes('OFFERTA UFFICIALE'),'Joao Mario non aggiornato');
assert(findTalk('como','market-chalobah','incoming')?.note.includes('5 milioni'),'Chalobah non aggiornato');
assert(findTalk('milan','milan-rafael-leao','outgoing')?.status.includes('GALATASARAY'),'Leao non aggiornato');
const names=ids.map(id=>resolvePlayer(id)?.playerName||id).map(x=>x.normalize('NFD').replace(/[\u0300-\u036f]/g,'').toLowerCase().replace(/[^a-z0-9]+/g,' ').trim());
assert(new Set(names).size===names.length,'nomi visualizzati duplicati');
assert(resolvePlayer('monza-pessina-mas')?.role==='C','Matteo Pessina non C');
assert(resolvePlayer('bologna-pessina-mas')?.role==='P','Massimo Pessina non P');
console.log(`Audit ioSudo V780 OK - rumor ${incoming+outgoing+other}, roster 739, catalogo 1123, SOS 57, tabellini 33, prestazioni 687, duplicati 0.`);
